-- Do not grant all authenticated users access to another client's orders.
create or replace function public.restaurant_is_owner(p_tenant text)
returns boolean language sql stable security invoker set search_path = '' as $$
 select exists (
 select 1 from public.restaurant_tenants t
 join public.memberships m on m.org_id=t.owner_org_id
 where t.id = p_tenant and m.user_id = (select auth.uid())
 and m.role in ('owner','admin','agency_owner','super_admin')
 );
$$;
revoke all on function public.restaurant_is_owner(text) from public;
grant execute on function public.restaurant_is_owner(text) to authenticated;

