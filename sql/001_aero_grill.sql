-- AI AutoTech restaurant module. New names only; no existing tables modified.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.restaurant_tenants (
  id text primary key,
  name text not null,
  currency text not null default 'ZAR',
  owner_org_id uuid not null references public.organizations(id),
  business_mode text not null default 'demo' check (business_mode in ('demo','live')),
  created_at timestamptz not null default now()
);
create table if not exists public.restaurant_menu_items (
  id integer generated by default as identity primary key,
  tenant_id text not null references public.restaurant_tenants(id),
  name text not null, category text not null, description text not null default '',
  price_cents integer not null check(price_cents between 0 and 10000000),
  available boolean not null default true,
  sort_order integer not null default 0
);
create table if not exists public.restaurant_orders (
  id uuid primary key default gen_random_uuid(),
  token uuid not null default gen_random_uuid(),
  tenant_id text not null references public.restaurant_tenants(id),
  customer_name text not null, phone text not null, notes text not null default '',
  fulfilment text not null check(fulfilment in ('Collection','Dine-in','Delivery')),
  source text not null default 'website' check(source in ('website','whatsapp','staff')),
  amount_cents integer not null check (amount_cents >= 0),
  payment_method text not null default 'cash',
  payment_status text not null default 'unpaid' check(payment_status in ('unpaid','pending','paid','failed')),
  status text not null default 'New' check(status in ('New','Preparing','Ready','Completed','Cancelled')),
  external_checkout_id text unique,
  created_at timestamptz not null default now()
);
create index if not exists restaurant_orders_tenant_time_idx on public.restaurant_orders(tenant_id,created_at desc);
create table if not exists public.restaurant_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.restaurant_orders(id) on delete cascade,
  menu_item_id integer not null references public.restaurant_menu_items(id),
  item_name text not null, price_cents integer not null,
  qty integer not null check(qty between 1 and 30)
);
create table if not exists public.restaurant_payment_events (
  event_id text primary key,
  checkout_id text not null,
  event_type text not null,
  received_at timestamptz not null default now()
);
create schema if not exists restaurant_private;
revoke all on schema restaurant_private from public, anon, authenticated;
create table if not exists restaurant_private.settings (
  id boolean primary key default true check (id),
  gateway_secret_hash text not null
);
create table if not exists restaurant_private.whatsapp_sessions (
  phone text primary key,
  cart jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

